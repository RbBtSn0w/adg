import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, writeFileSync, symlinkSync, cpSync, readFileSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { execFileSync } from 'node:child_process';
import { analyzeRelease } from '../.github/release-train/release-analysis.mjs';
const analyze = (cwd, env = process.env) => analyzeRelease({ cwd, env, outputPath: null });
test('real engine analyzes exact local main without credentials, services, builds or new tags', async () => {
  const cwd = mkdtempSync(join(tmpdir(), 'release-engine-'));
  const git = (...args) => execFileSync('git', args, { cwd, encoding: 'utf8' }).trim();
  git('init', '-b', 'main'); git('config', 'user.name', 'Fixture'); git('config', 'user.email', 'fixture@example.invalid');
  writeFileSync(join(cwd, 'package.json'), JSON.stringify({ name: '@scope/public-fixture', repository: {url:'https://github.com/owner/public-fixture.git'}, version: '1.0.0', scripts: { build: 'exit 99' } }));
  const config = JSON.parse(readFileSync('.releaserc.json'));
  config.tagFormat = 'v${version}';
  mkdirSync(join(cwd, 'scripts'));
  mkdirSync(join(cwd, '.github'));
  cpSync('.github/release-train', join(cwd, '.github/release-train'), { recursive: true });
  git('config', 'remote.origin.url', 'https://github.com/owner/public-fixture.git');
  writeFileSync(join(cwd, '.releaserc.json'), JSON.stringify(config));
  symlinkSync(resolve('node_modules'), join(cwd, 'node_modules'), 'dir');
  git('add', 'package.json', '.releaserc.json'); git('commit', '-m', 'chore: baseline'); git('tag', 'v1.0.0');
  git('commit', '--allow-empty', '-m', 'chore: Add Legacy Metadata');
  const noRelease = await analyze(cwd, { ...process.env, GH_TOKEN: 'must-not-reach-engine', NPM_TOKEN: 'must-not-reach-engine' });
  assert.equal(noRelease.version, null); assert.equal(noRelease.baseline_tag, 'v1.0.0');
  git('commit', '--allow-empty', '-m', 'feat!: changed contract');
  const release = await analyze(cwd);
  assert.equal(release.version, '2.0.0'); assert.equal(release.candidate_sha, git('rev-parse', 'HEAD'));
  assert.equal(git('tag'), 'v1.0.0');
});
